"""Generate the leg-height and roll TinyMPC model and solver cache."""

import argparse
from dataclasses import asdict
import json
from pathlib import Path
import sys

import numpy as np
from scipy.linalg import expm, solve_discrete_are

ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = ROOT / "chassis/tinympc/generated"
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "tools/leg_lqr"))
from dynamics import state_space
from model_params import PHYSICAL

# MPC tuning
DT = 0.01  # Seconds per prediction step and solve period.
INTERVALS = 15  # Prediction duration = DT * INTERVALS.
FORCE_MIN = 15.0  # N, total support per leg
FORCE_MAX = 200.0
DELTA_MAX = 60.0  # N per MPC step
Q_DIAG = (1_500_000.0, 600.0, 10_000_000.0, 2000.0)  # roll, droll, H, dH
FORCE_WEIGHT = (0.1, 0.08) #惩罚左右腿相对平衡支撑力的偏差
DELTA_WEIGHT = 1.0e-5  # 相邻两拍的力变化
RHO = 3.0
SCALE = np.array([0.1, 1.0, 0.1, 1.0, 100.0, 100.0])


def design(sample_time):
    ac, bc, _, equilibrium = state_space()
    zoh = expm(np.block([[ac, bc], [np.zeros((2, 6))]]) * sample_time)
    ad, bd = zoh[:4, :4], zoh[:4, 4:]

    # State: [roll, droll, H, dH, previous force deviations]. Input: force increments.
    a = np.block([[ad, bd], [np.zeros((2, 4)), np.eye(2)]])
    b = np.vstack((bd, np.eye(2)))
    a = a * SCALE[None, :] / SCALE[:, None]
    b = b * SCALE[4:][None, :] / SCALE[:, None]
    q = np.array([*Q_DIAG, *FORCE_WEIGHT]) * SCALE**2 / 10_000.0
    r = np.full(2, DELTA_WEIGHT)

    pinf = solve_discrete_are(a, b, np.diag(q + RHO), np.diag(r + RHO))
    inv = np.linalg.inv(np.diag(r + RHO) + b.T @ pinf @ b)
    k = inv @ b.T @ pinf @ a
    return float(equilibrium[0]), {
        "a": a, "b": b, "q": q, "r": r, "pinf": pinf, "k": k, "inv": inv,
        "ambkt": (a - b @ k).T, "scale": SCALE,
    }


def initializer(value):
    if value.ndim == 1:
        return "{" + ", ".join(f"{v:.10e}f" for v in value) + "}"
    rows = "\n".join(f"    {initializer(row)}," for row in value)
    return "{\n" + rows + "\n}"


def render_header(equilibrium, data, sample_us):
    lines = [
        "#pragma once",
        "",
        '#include "horizon.h"',
        "",
        "// Generated by tools/tinympc/generate.py.",
        "namespace chassis::tinympc::model",
        "{",
        f"inline constexpr unsigned sample_us = {sample_us}U;",
        "inline constexpr float sample_time = sample_us * 1.0e-6f;",
        "inline constexpr unsigned intervals = TINY_STEPS;",
        "inline constexpr unsigned knots = TINY_KNOTS;",
        f"inline constexpr float equilibrium_force = {equilibrium:.10e}f;",
        f"inline constexpr float min_force = {FORCE_MIN:.10e}f;",
        f"inline constexpr float max_force = {FORCE_MAX:.10e}f;",
        f"inline constexpr float max_delta = {DELTA_MAX:.10e}f;",
        f"inline constexpr float rho = {RHO:.10e}f;",
        "",
    ]
    for name, value in data.items():
        shape = "".join(f"[{n}]" for n in value.shape)
        lines.append(f"inline constexpr float {name}{shape} = {initializer(value)};")
    lines.append("} // namespace chassis::tinympc::model")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    parser.add_argument("--check", action="store_true", help="Verify existing generated files")
    args = parser.parse_args()
    if type(INTERVALS) is not int or INTERVALS < 1:
        parser.error("INTERVALS must be a positive integer")
    if not 1 <= DT * 1_000_000 <= 0xFFFFFFFF:
        parser.error("DT must be between 1 and 4294967295 microseconds")
    sample_us = round(DT * 1_000_000)
    sample_time = sample_us / 1_000_000
    equilibrium, data = design(sample_time)
    report = {
        "source_revision": "feat/leg-roll-tinympc-100hz@17a7701",
        "sample_time": sample_time,
        "intervals": INTERVALS,
        "knots": INTERVALS + 1,
        "state_order": ["roll", "droll", "H", "dH", "previous_dF_left", "previous_dF_right"],
        "input_order": ["delta_F_left", "delta_F_right"],
        "physical": dict(asdict(PHYSICAL), mass=PHYSICAL.mass),
        "equilibrium_force": equilibrium,
        "force_bounds_N": [FORCE_MIN, FORCE_MAX],
        "delta_force_N": DELTA_MAX,
        "rho": RHO,
        **{key: value.tolist() for key, value in data.items()},
    }
    outputs = {
        "horizon.h": (
            "#pragma once\n\n"
            "// Generated by tools/tinympc/generate.py. Shared by the C and C++ sources.\n"
            f"enum {{ TINY_STEPS = {INTERVALS}, TINY_KNOTS = TINY_STEPS + 1 }};\n"
        ),
        "leg_mpc_coeffs.hpp": render_header(equilibrium, data, sample_us),
        "leg-mpc-report.json": json.dumps(report, indent=2) + "\n",
    }
    for name, content in outputs.items():
        path = args.output_dir / name
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if args.check:
            if current != content:
                raise SystemExit(f"Stale or missing output: {path}")
        elif current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    print(f"Leg MPC model {'verified' if args.check else 'generated'} in {args.output_dir}")


if __name__ == "__main__":
    main()
